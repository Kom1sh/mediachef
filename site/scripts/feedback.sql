-- Таблица сообщений с формы обратной связи. Применяется руками, один раз:
--   npx wrangler d1 execute mediachef-crawlers --remote --file=scripts/feedback.sql
-- Повторный прогон безопасен.
--
-- Живёт в той же базе, что журнал роботов: две таблицы на бесплатном тарифе
-- дешевле двух баз, а связи между ними нет никакой — только общий доступ.

CREATE TABLE IF NOT EXISTS feedback (
  id INTEGER PRIMARY KEY,
  -- Unix-миллисекунды.
  at INTEGER NOT NULL,
  -- «bug» или «idea» — то, что человек выбрал сам. Приходит из формы, поэтому
  -- проверяется в воркере по белому списку.
  kind TEXT NOT NULL,
  message TEXT NOT NULL,
  -- Куда ответить. Необязательно: человек, который просто хочет сообщить о
  -- поломке, не должен оставлять адрес ради этого.
  contact TEXT,
  -- Версия и система приложения, если форму открыли из него. Без них
  -- «не работает конвертация» не разобрать, а спрашивать вдогонку — потерять
  -- половину отвечающих.
  version TEXT,
  platform TEXT,
  -- Язык, на котором человек писал: подсказка, на каком отвечать.
  locale TEXT,
  -- Контекст: маркер упавшей задачи или экран, откуда открыли форму.
  context TEXT
);

-- IP, User-Agent, страна и сеть здесь НЕ хранятся намеренно. Журналу роботов
-- они нужны, чтобы поймать подделку User-Agent; здесь это письмо от человека, и
-- собирать про него данные, о которых он не просил, значило бы противоречить
-- обещанию продукта. Хранится ровно то, что он сам написал, и то, что нужно,
-- чтобы понять его сообщение.

CREATE INDEX IF NOT EXISTS feedback_at ON feedback (at);

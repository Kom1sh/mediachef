/**
 * Кнопка «рассказать, что не так».
 *
 * Зачем понадобилась: у приложения не было ни одной внешней ссылки. Человек,
 * у которого что-то не сработало, физически не мог никуда пойти из окна — а
 * приходят люди по рекомендации ассистентов, репозитория они не видели и искать
 * его не станут.
 *
 * Устройство намеренно скучное: мы открываем в браузере форму, уже заполненную
 * версией и системой, и на этом наша роль кончается. Ничего не отправляется само
 * — человек читает готовый текст, правит и жмёт отправку сам. Для программы,
 * которая обещает, что файлы не уезжают никуда, любой автоматический канал
 * «наружу» был бы подрывом этого обещания, даже безобидный.
 *
 * Версия и система подставлены не для красоты: «не работает конвертация» без них
 * не разобрать, а спрашивать их вдогонку — потерять половину отвечающих.
 */
import { openUrl } from "@tauri-apps/plugin-opener";
import { getVersion } from "@tauri-apps/api/app";
import { platformInfo } from "./ipc";

const NEW_ISSUE = "https://github.com/Kom1sh/mediachef/issues/new";

// Метки берём те, что в репозитории уже есть, а не свои: `bug` и `enhancement`
// — стандартный набор GitHub, и ссылка с несуществующей меткой молча теряет её.
const LABEL = { bug: "bug", idea: "enhancement" } as const;

/**
 * Открывает форму отчёта. `kind` попадает в метку, чтобы разбирать поток:
 * поломка и пожелание живут в разных очередях.
 *
 * Ошибки проглатываются молча: не открылся браузер — это неприятно, но
 * показывать поверх этого ещё одну ошибку означало бы сообщать человеку
 * о неудаче его попытки сообщить о неудаче.
 */
export async function openFeedback(kind: "bug" | "idea"): Promise<void> {
  const [version, platform] = await Promise.all([
    getVersion().catch(() => ""),
    platformInfo().catch(() => ""),
  ]);

  // Заголовок пустой намеренно: человек напишет своими словами, а подставленный
  // за него текст чаще всего так и уезжает неотредактированным.
  const body = [
    "",
    "",
    "---",
    `MediaChef ${version || "?"} · ${platform || "?"}`,
  ].join("\n");

  const url = `${NEW_ISSUE}?labels=${LABEL[kind]}&body=${encodeURIComponent(body)}`;
  try {
    await openUrl(url);
  } catch {
    // см. выше
  }
}

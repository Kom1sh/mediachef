/**
 * Кнопка «рассказать, что не так».
 *
 * Зачем понадобилась: у приложения не было ни одной внешней ссылки. Человек,
 * у которого что-то не сработало, физически не мог никуда пойти из окна — а
 * приходят люди по рекомендации ассистентов, репозитория они не видели и искать
 * его не станут.
 *
 * Письмо, а не форма на GitHub: от регистрации на GitHub пришедший по
 * рекомендации отказывается чаще, чем пишет письмо. Шаблоны issue в репозитории
 * остались — они для тех, кто и так пришёл туда.
 *
 * Устройство намеренно скучное: мы открываем почтовый клиент с уже заполненным
 * письмом, и на этом наша роль кончается. Ничего не отправляется само — человек
 * читает готовый текст, правит и жмёт отправку сам. Для программы, которая
 * обещает, что файлы не уезжают никуда, любой автоматический канал «наружу» был
 * бы подрывом этого обещания, даже безобидный.
 *
 * Версия и система подставлены не для красоты: «не работает конвертация» без них
 * не разобрать, а спрашивать их вдогонку — потерять половину отвечающих.
 */
import { openUrl } from "@tauri-apps/plugin-opener";
import { getVersion } from "@tauri-apps/api/app";
import { platformInfo } from "./ipc";

/** Пересылается на ящик поддержки через Cloudflare Email Routing. */
export const FEEDBACK_EMAIL = "hello@mediachef.app";

/**
 * Открывает письмо с заполненной темой и подписью о сборке.
 *
 * `subject` приходит из текстов языка — это подпись нажатой кнопки, то есть уже
 * переведённая и ровно та формулировка, которую человек выбрал. Отдельная строка
 * под тему была бы одиннадцатым переводом того же самого.
 *
 * Ошибки проглатываются молча: не открылся клиент — неприятно, но показывать
 * поверх этого ещё одну ошибку означало бы сообщать человеку о неудаче его
 * попытки сообщить о неудаче. Адрес на этот случай написан текстом в подсказке
 * рядом с кнопкой — его можно скопировать руками.
 */
export async function openFeedback(subject: string): Promise<void> {
  const [version, platform] = await Promise.all([
    getVersion().catch(() => ""),
    platformInfo().catch(() => ""),
  ]);

  // Пустые строки сверху — курсор встаёт туда, где человеку писать. Подпись
  // отделена чертой, чтобы её не приняли за часть своего текста и не стёрли.
  const body = ["", "", "---", `MediaChef ${version || "?"} · ${platform || "?"}`].join("\n");

  const url =
    `mailto:${FEEDBACK_EMAIL}` +
    `?subject=${encodeURIComponent(`MediaChef — ${subject}`)}` +
    `&body=${encodeURIComponent(body)}`;

  try {
    await openUrl(url);
  } catch {
    // см. выше
  }
}

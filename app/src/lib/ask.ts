/**
 * Один раз спросить человека, как ему программа.
 *
 * Зачем. За первые две недели программу скачали около семидесяти человек и не
 * написал ни один. Форма обратной связи есть, но открывается она только из
 * карточки упавшей задачи и из настроек — то есть её видят те, у кого сломалось,
 * и те, кто сам полез в настройки. Тот, у кого всё работает, не видит её никогда,
 * а именно его «чего не хватает» и нужно.
 *
 * Как. После третьей успешной задачи — не при запуске, а в момент, когда
 * программа только что сделала то, ради чего её открыли, — появляется полоса с
 * двумя предложениями: написать отзыв или поставить звезду на GitHub. Любое
 * действие, включая крестик, убирает её навсегда. Спросить второй раз того, кто
 * уже ответил или отказался, — это уже не вопрос, а реклама.
 *
 * Хранение — `localStorage` webview, а не файл настроек: это не настройка, ни
 * показывать её, ни синхронизировать нечего, а Rust-сторона ради одного счётчика
 * получила бы поле, миграцию и санитайзер. Хранилище переживает перезапуск и
 * обновление (у приложения тот же идентификатор). Если оно недоступно — полоса
 * просто не появится: лучше не спросить никогда, чем спрашивать при каждом запуске.
 */

/** После какой по счёту успешной задачи спрашивать. */
export const ASK_AFTER = 3;

const COUNT_KEY = "mc-jobs-done";
const ANSWERED_KEY = "mc-ask-answered";

/** Тот кусок `Storage`, который здесь нужен, — чтобы в тестах подставить свой. */
export type AskStorage = Pick<Storage, "getItem" | "setItem">;

/** Спрашивать ли сейчас: порог пройден и человек ещё не отвечал. */
export function shouldAsk(count: number, answered: boolean): boolean {
  return !answered && count >= ASK_AFTER;
}

/**
 * Засчитывает успешную задачу и отвечает, пора ли показать полосу.
 *
 * Любая ошибка хранилища — «не спрашивать»: без записи счётчик не растёт, и
 * показанная из-за этого полоса стала бы появляться после каждой задачи.
 */
export function recordJobDone(storage: AskStorage): boolean {
  try {
    if (storage.getItem(ANSWERED_KEY)) return false;
    const count = (Number(storage.getItem(COUNT_KEY)) || 0) + 1;
    storage.setItem(COUNT_KEY, String(count));
    return shouldAsk(count, false);
  } catch {
    return false;
  }
}

/** Человек ответил — любым способом. Больше не спрашиваем. */
export function markAnswered(storage: AskStorage): void {
  try {
    storage.setItem(ANSWERED_KEY, "1");
  } catch {
    // Не записалось — полоса уже закрыта в этом сеансе, а в следующем появится
    // только после очередной успешной задачи. Показывать ошибку ради этого незачем.
  }
}

/**
 * `localStorage` webview за тем же узким интерфейсом. Обращение к глобалу —
 * внутри методов, а не при импорте: в контексте, где хранилище запрещено, сам
 * доступ к `localStorage` бросает, и так это исключение ловит `recordJobDone`.
 */
export const appStorage: AskStorage = {
  getItem: k => localStorage.getItem(k),
  setItem: (k, v) => localStorage.setItem(k, v),
};

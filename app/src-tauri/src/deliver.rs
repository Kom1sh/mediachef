//! Доставка надиктованного: буфер обмена, печать в активное поле, уведомления.
//!
//! ## Два способа, и почему не три
//!
//! Был третий — вставка через синтетический `Cmd+V`. Он **уронил приложение**
//! на первом же живом применении: в журнале диктовки последняя строка перед
//! перезапуском процесса — остановка записи, и ни одной строки о доставке.
//! Падало внутри отправки сочетания с зажатым модификатором.
//!
//! Чинить его было бы работой ради режима, который ничего не добавляет: печать
//! (`type_into_active_window`) доставляет текст туда же, в активное поле, и при
//! этом не затирает буфер обмена. Единственное преимущество вставки — скорость
//! на длинном тексте, а диктуют фразами. Поэтому режим снят целиком, а не
//! отложен: висящий в списке пункт, который валит программу, хуже отсутствующего.
//!
//! ## Разрешение «Универсальный доступ»
//!
//! Печать в чужое окно — это синтетический ввод, и macOS требует за него
//! разрешения. Прежнее решение было «тогда не делаем вовсе»: разрешение
//! слетает при обновлении неподписанного приложения, и ввод **молча**
//! перестанет работать.
//!
//! Довод оказался с дырой. Молчание — не свойство задачи, а свойство
//! реализации: система умеет отвечать на вопрос «а доступ-то выдан?»
//! (`AXIsProcessTrusted`). Спрашиваем перед каждой попыткой и говорим вслух,
//! когда доступа нет, — и возражение исчезает.
//!
//! Осталась настоящая цена, и она невелика: после каждого обновления
//! приложения разрешение придётся выдать заново. Мы про это скажем, а не
//! оставим человека гадать, почему текст перестал появляться.
//!
//! Уведомления шлются отсюда, из Rust, а не из вебвью. В остальном приложении
//! их шлёт фронтенд, но здесь так нельзя: диктовкой пользуются, когда окно
//! MediaChef закрыто или свёрнуто, и полагаться на живой вебвью — значит
//! иногда не сказать человеку ничего.

use tauri::AppHandle;
use tauri_plugin_clipboard_manager::ClipboardExt;
use tauri_plugin_notification::NotificationExt;

/// Кладёт текст в буфер обмена.
///
/// Прежнее содержимое не восстанавливается, и это осознанно: восстановление
/// через сотню миллисекунд после вставки — классический источник гонок с
/// приложением-получателем, которое к тому моменту могло ещё не прочитать
/// буфер. Предсказуемо затереть лучше, чем иногда подсунуть старое.
pub fn to_clipboard(app: &AppHandle, text: &str) -> Result<(), String> {
    app.clipboard()
        .write_text(text.to_string())
        .map_err(|e| e.to_string())
}

/// Выдан ли «Универсальный доступ» — без него синтетический ввод молча не
/// сработает.
///
/// Спрашиваем систему **перед каждой** попыткой, а не один раз при старте:
/// разрешение можно отозвать в любой момент, и оно слетает при обновлении
/// неподписанного приложения. Проверка стоит микросекунды, а её отсутствие
/// стоило бы человеку неотличимого от поломки молчания.
#[cfg(target_os = "macos")]
pub fn can_paste() -> bool {
    // Своя привязка вместо целого крейта: нужна ровно одна функция без
    // аргументов, и тянуть ради неё зависимость не за чем.
    #[link(name = "ApplicationServices", kind = "framework")]
    extern "C" {
        fn AXIsProcessTrusted() -> bool;
    }
    unsafe { AXIsProcessTrusted() }
}

/// На Windows и Linux разрешения такого рода нет: там вставка либо работает,
/// либо падает с ошибкой от самой `enigo`.
#[cfg(not(target_os = "macos"))]
pub fn can_paste() -> bool {
    true
}

/// Открывает нужный раздел системных настроек macOS.
///
/// Ссылка, а не инструкция «зайдите в настройки, приватность, дальше вниз»:
/// путь туда достаточно длинный, чтобы человек по дороге передумал.
#[cfg(target_os = "macos")]
pub fn open_accessibility_settings() {
    // Два адреса, а не один, и оба пробуются по очереди. Идентификатор раздела
    // менялся: `com.apple.preference.security` — язык старой «Системных
    // настроек», `com.apple.settings.PrivacySecurity.extension` — нынешней.
    // Какой сработает, зависит от версии macOS, а `open` про неудачу молчит:
    // он возвращает ноль, даже когда раздел не раскрылся. Поэтому не выбираем,
    // а зовём оба — лишний вызов ничего не портит, а промах оставил бы человека
    // перед окном с инструкцией и без настроек.
    for url in [
        "x-apple.systempreferences:com.apple.settings.PrivacySecurity.extension?Privacy_Accessibility",
        "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility",
    ] {
        let _ = std::process::Command::new("open").arg(url).spawn();
    }
}

#[cfg(not(target_os = "macos"))]
pub fn open_accessibility_settings() {}

/// Печатает текст прямо в активное поле ввода, **не трогая буфер обмена**.
///
/// Единственный способ доставить текст туда, где стоит курсор. Буфер при этом
/// остаётся нетронутым, и это не мелочь: при диктовке несколько раз в час
/// затирание буфера означало бы, что им нельзя пользоваться вообще —
/// скопировал ссылку, надиктовал фразу, ссылки нет.
///
/// Цена: символы уходят событием ввода, поэтому очень длинный текст появляется
/// не мгновенно, и приложение-получатель может успеть вмешаться —
/// автодополнение в редакторе кода, например. На фразах, которыми диктуют, это
/// незаметно.
pub fn type_into_active_window(text: &str) -> Result<(), String> {
    if !can_paste() {
        return Err("no_accessibility".into());
    }
    use enigo::{Enigo, Keyboard, Settings};
    let mut enigo = Enigo::new(&Settings::default()).map_err(|e| e.to_string())?;
    // `text` целиком, а не по символу: на macOS это один вызов
    // CGEventKeyboardSetUnicodeString, который умеет кириллицу и эмодзи вне
    // зависимости от текущей раскладки. Посимвольная эмуляция клавиш зависела
    // бы от раскладки и на русской выдала бы латиницу.
    enigo.text(text).map_err(|e| e.to_string())
}

/// Нажимает Enter в активном окне.
///
/// Отдельно от [`type_into_active_window`] и всегда после него: Enter — это
/// необратимое действие в чужом приложении. Отправленное сообщение не вернуть,
/// выполненную в терминале команду тем более, поэтому решение «жать» принимает
/// вызывающий и только когда текст действительно доставлен.
pub fn press_enter() -> Result<(), String> {
    if !can_paste() {
        return Err("no_accessibility".into());
    }
    use enigo::{Direction, Enigo, Key, Keyboard, Settings};
    let mut enigo = Enigo::new(&Settings::default()).map_err(|e| e.to_string())?;
    enigo
        .key(Key::Return, Direction::Click)
        .map_err(|e| e.to_string())
}

/// Зачем понадобилось разрешение — от этого зависит текст окна и набор кнопок.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PermissionReason {
    /// Не удалось напечатать текст в активное поле.
    Typing,
    /// Не удалось поставить перехватчик клавиатуры для клавиши-триггера.
    Hotkey,
}

/// Что человек выбрал в окне про недостающее разрешение.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PermissionChoice {
    /// Открыть системные настройки и включить доступ.
    OpenSettings,
    /// Класть текст в буфер и не просить больше.
    UseClipboard,
    /// Выключить диктовку целиком.
    TurnOff,
}

/// Окно с объяснением, что делать с недостающим разрешением.
///
/// Уведомления здесь мало, и это выяснилось на живых прогонах. Уведомление
/// исчезает через несколько секунд, его легко пропустить, и в нём нельзя
/// сказать главного: **разрешения мало, нужен ещё и перезапуск**. macOS
/// применяет выданный доступ только к новому запуску приложения, поэтому
/// человек, который честно включил переключатель и попробовал снова, получает
/// ровно тот же отказ — и решает, что программа сломана.
///
/// Окно одно на оба повода — печать и клавиша-триггер, — потому что
/// разрешение одно и шаги те же; различаются только объяснение и кнопки.
///
/// Блокирующий вызов, поэтому звать только из рабочего потока: на главном он
/// повесил бы приложение.
pub fn ask_about_permission(app: &AppHandle, reason: PermissionReason) -> PermissionChoice {
    use tauri_plugin_dialog::{
        DialogExt, MessageDialogButtons, MessageDialogKind, MessageDialogResult,
    };

    // Подписи кнопок — константами, потому что по ним же разбирается ответ.
    // Плагин для кнопок с своими подписями возвращает не `Ok`/`Cancel`, а
    // `Custom(подпись)`. Первая редакция ждала `Ok`, и нажатие «Понятно»
    // проваливалось в запасную ветку — «класть в буфер». Так доставка дважды
    // переключалась на буфер за спиной у человека, который жал ровно то,
    // что ему сказали.
    const BTN_OK: &str = "Понятно";
    const BTN_CLIPBOARD: &str = "Класть в буфер";
    // Настройки открываем СРАЗУ, не дожидаясь кнопки. Прошлая редакция вешала
    // это на кнопку «Открыть настройки», и человек остался и без настроек, и
    // без понимания, почему: то ли кнопка не та, то ли не сработала. Раздел уже
    // открыт за окном — и тогда любая нажатая кнопка ведёт к понятному итогу.
    open_accessibility_settings();

    let (message, buttons) = match reason {
        PermissionReason::Typing => (
            "Системные настройки уже открыты за этим окном.\n\n\
             1. Найдите там MediaChef и включите переключатель.\n\
             2. Перезапустите MediaChef — без перезапуска разрешение не подействует.\n\n\
             Переключатель уже включён? Выключите и включите его заново: после обновления macOS \
             считает MediaChef новым приложением, а старая галка относится к прежней копии.\n\n\
             Не нужна печать прямо в поле? Нажмите «Класть в буфер»: текст будет копироваться, \
             и вы вставите его сами через Cmd+V.",
            // Две кнопки, а не три. С тремя непонятно, какая из них какая:
            // macOS раскладывает их справа налево, и «первая» на экране
            // оказывается не первой в коде. Выключение диктовки живёт в
            // настройках приложения, где ему и место.
            MessageDialogButtons::OkCancelCustom(BTN_OK.into(), BTN_CLIPBOARD.into()),
        ),
        PermissionReason::Hotkey => (
            "Без него диктовка не слышит клавишу-триггер и не может печатать в поле. \
             Системные настройки уже открыты за этим окном.\n\n\
             1. Найдите там MediaChef и включите переключатель.\n\
             2. Перезапустите MediaChef — без перезапуска разрешение не подействует.\n\n\
             Переключатель уже включён? Выключите и включите его заново: после обновления macOS \
             считает MediaChef новым приложением, а старая галка относится к прежней копии.",
            // Одна кнопка: без разрешения не заработает ни триггер, ни печать,
            // и предлагать здесь буфер обмена было бы обманом.
            MessageDialogButtons::OkCustom(BTN_OK.into()),
        ),
    };

    let answer = app
        .dialog()
        .message(message)
        .title("Диктовка: включите «Универсальный доступ»")
        .kind(MessageDialogKind::Warning)
        .buttons(buttons)
        .blocking_show_with_result();

    match answer {
        // Только явное нажатие на «Класть в буфер» меняет настройку. Всё
        // остальное — «Понятно», крестик, Escape — оставляет всё как есть:
        // молча переключать способ доставки за спиной у человека нельзя,
        // ровно на этом первая редакция и погорела.
        MessageDialogResult::Custom(label) if label == BTN_CLIPBOARD => {
            PermissionChoice::UseClipboard
        }
        _ => PermissionChoice::OpenSettings,
    }
}

/// Показывает уведомление. Отказ проглатываем: не сказать про расшифровку
/// обиднее, чем не сказать про то, что не удалось сказать про расшифровку.
pub fn notify(app: &AppHandle, title: &str, body: &str) {
    let _ = app.notification().builder().title(title).body(body).show();
}

/// Короткая выжимка расшифровки для тела уведомления.
///
/// Уведомление обязано показать, что именно попало в буфер: иначе человек не
/// отличит удачную диктовку от чужого текста, лежавшего там раньше. Но целую
/// фразу система всё равно обрежет по-своему и на полуслове, поэтому режем
/// сами и ставим многоточие.
pub fn preview(text: &str, max_chars: usize) -> String {
    let mut out: String = text.chars().take(max_chars).collect();
    if text.chars().count() > max_chars {
        out.push('…');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn preview_keeps_short_text_whole() {
        assert_eq!(preview("привет", 40), "привет");
    }

    #[test]
    fn preview_truncates_and_marks() {
        let long = "а".repeat(100);
        let p = preview(&long, 40);
        assert_eq!(p.chars().count(), 41, "сорок знаков плюс многоточие");
        assert!(p.ends_with('…'));
    }

    /// Режем по символам, а не по байтам: кириллица многобайтовая, и обрезка
    /// по байту дала бы битую строку.
    #[test]
    fn preview_cuts_on_char_boundary() {
        let p = preview("щщщщщ", 3);
        assert_eq!(p, "щщщ…");
    }
}
